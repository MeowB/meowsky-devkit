# Shape data uses one character per square pixel: # is the terminal foreground,
# and . is transparent. Two pixel rows become one terminal row of half blocks.
# This ASCII source also loads correctly in Windows PowerShell 5.1.
$script:MeowskyCatArt = @{
  standing = @(
  ''
  ''
  '...............................................###'
  '.................................................##'
  '..........#.....#................................##'
  '.........###...###...............................##'
  '........###########.............................##'
  '.......#############..........................###'
  '.......####.#########......................####'
  '.....##################################.####'
  '.......##################################'
  '..........###############################'
  '............#############################'
  '.................#######################'
  '...................###################'
  '....................####..........#####'
  '....................###.##........###.##'
  '....................##..##........##..##'
  '....................##..##........##..##'
  '....................##..##........##..##'
  '....................##..##........##..##'
  '....................##..##........##..##'
  '..................#####.####....#####.#####'
  ''
  ''
  ''
  )
  seated = @(
  ''
  ''
  ''
  '...........#.....#'
  '..........###...###'
  '.........###########'
  '........#############'
  '........####.########'
  '........##############'
  '.......###############'
  '........##############'
  '...............########'
  '.................#######'
  '..................#######'
  '..................###...##.........###'
  '.................####...###..........###'
  '................#####...####...........###'
  '...............####.....#####...........##'
  '..............#####.....######..........##'
  '.............######.....#######........##'
  '............#######.....########.....###'
  '...........########..###########..####'
  '..........#########..##############'
  '..........#########..############'
  '...........######..###....####'
  '..........########.###....#####'
  '.........##############..#########'
  ''
  )
}

function Get-MeowskyCatPixels {
  param([ValidateSet('standing', 'seated')][string]$Pose = 'seated')

  $source = $script:MeowskyCatArt[$Pose]
  $width = if ($Pose -eq 'standing') { 54 } else { 46 }
  return ,@($source | ForEach-Object { ,($_.PadRight($width, '.').ToCharArray()) })
}

